import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../miniprogram');
const start = '/* large-screen:start — generated by scripts/generate-large-screen-styles.mjs */';
const end = '/* large-screen:end */';
// Graph geometry and badges retain rpx: their common parent transform controls
// the rendered pixel size. Only surrounding UI uses the 375px design baseline.
const graph = /\.(?:graph-canvas|graph-movable|graph-unit-probe|relation-(?:line|spouse|trunk|drop|rail|flow)|line-crossing|family-junction|flow-runner|person-node|node-|branch-count|life-status-badge|child-rank-badge|zoom-|gender-avatar|gender-badge|gender-node-badge)/;

function files(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap(entry => {
    const target = path.join(dir, entry.name);
    return entry.isDirectory() ? files(target) : target.endsWith('.wxss') ? [target] : [];
  });
}

function overrides(source) {
  const rules = [];
  // Parse brace nesting so keyframes and existing media blocks are never
  // mistaken for top-level selectors. This generator has no runtime dependency.
  const clean = source.replace(/\/\*[\s\S]*?\*\//g, '');
  let cursor = 0;
  while (cursor < clean.length) {
    const opening = clean.indexOf('{', cursor);
    if (opening < 0) break;
    const selector = clean.slice(cursor, opening).replace(/@import[^;]+;/g, '').trim();
    let depth = 1, closing = opening + 1;
    while (closing < clean.length && depth) {
      if (clean[closing] === '{') depth += 1;
      else if (clean[closing] === '}') depth -= 1;
      closing += 1;
    }
    const body = clean.slice(opening + 1, closing - 1);
    cursor = closing;
    if (selector.startsWith('@') || graph.test(selector)) continue;
    const declarations = body.split(';').map(value => value.trim()).filter(value => /-?\d*\.?\d+rpx\b/.test(value));
    if (!declarations.length) continue;
    const converted = declarations.map(value => value.replace(/(-?\d*\.?\d+)rpx\b/g, (_, number) => Number(number) / 2 + 'px'));
    rules.push('  ' + selector.replace(/\s+/g, ' ') + ' { ' + converted.join('; ') + '; }');
  }
  return rules;
}

for (const file of files(root)) {
  if (file.endsWith('/styles/large-screen.wxss')) continue;
  const existing = fs.readFileSync(file, 'utf8');
  const source = existing.replace(/\n?\/\* large-screen:start[\s\S]*?\/\* large-screen:end \*\/\n?/g, '\n');
  const layout = source.indexOf('/* large-screen:layout */');
  const base = layout < 0 ? source : source.slice(0, layout);
  const rules = overrides(base);
  const block = rules.length ? '\n' + start + '\n@media (min-width: 600px) {\n' + rules.join('\n') + '\n}\n' + end + '\n' : '';
  // Place generated baseline before handwritten layout rules, preserving the
  // latter's deliberate widths, heights, and minimum touch target sizes.
  const output = (base.trimEnd() + block + (layout < 0 ? '' : '\n' + source.slice(layout))).trimEnd() + '\n';
  if (output !== existing) fs.writeFileSync(file, output);
}
