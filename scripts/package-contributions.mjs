import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const root = resolve(import.meta.dirname, '..');
const requireVite = createRequire(realpathSync(resolve(root, 'admin/node_modules/vite/package.json')));
const { minifySync } = await import(pathToFileURL(requireVite.resolve('rolldown/utils')));
const checking = process.argv.includes('--check');
for (const [name, targetName] of [["cache.js", "miniprogram/utils/contribution-cache.js"], ["child-rank.js", "miniprogram/utils/child-rank.js"], ["kinship.js", "miniprogram/utils/kinship.js"], ["entry.js", "miniprogram/utils/contribution-entry.js"]]) {
  const input = readFileSync(resolve(root, 'assets/contributions', name), 'utf8');
  const result = minifySync(name, input, { compress: true, mangle: { toplevel: true, reserved: ['module', 'exports', 'require'] } });
  if (result.errors && result.errors.length) throw new Error(JSON.stringify(result.errors));
  const output = '// Generated by scripts/package-contributions.mjs; edit assets/contributions/' + name + '\n' + result.code + '\n';
  const target = resolve(root, targetName);
  if (checking) {
    if (readFileSync(target, 'utf8') !== output) throw new Error('资料编写发布副本不同步：' + name);
  } else writeFileSync(target, output);
}
console.log('资料编写可维护源码与压缩副本' + (checking ? '一致' : '已同步'));
