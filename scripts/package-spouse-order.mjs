import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const root = resolve(import.meta.dirname, '..');
const requireVite = createRequire(realpathSync(resolve(root, 'admin/node_modules/vite/package.json')));
const { minifySync } = await import(pathToFileURL(requireVite.resolve('rolldown/utils')));
const checking = process.argv.includes('--check');
for (const name of ['spouse-order.js', 'spouse-order-panel.js', 'member-actions.js']) {
  const input = readFileSync(resolve(root, 'assets/spouse-order', name), 'utf8');
  const result = minifySync(name, input, { compress: true, mangle: { toplevel: true, reserved: ['module', 'exports', 'require'] } });
  if (result.errors && result.errors.length) throw new Error(JSON.stringify(result.errors));
  const output = '// Generated by scripts/package-spouse-order.mjs; edit assets/spouse-order/' + name + '\n' + result.code + '\n';
  const target = resolve(root, 'miniprogram/utils', name);
  if (checking) {
    if (readFileSync(target, 'utf8') !== output) throw new Error('夫妻排序发布副本不同步：' + name);
  } else writeFileSync(target, output);
}
console.log('夫妻排序可维护源码与压缩副本' + (checking ? '一致' : '已同步'));
