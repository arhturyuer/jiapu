import { readFileSync, writeFileSync, realpathSync } from 'node:fs';
import { resolve } from 'node:path';
import { createRequire } from 'node:module';
import { pathToFileURL } from 'node:url';
const root = resolve(import.meta.dirname, '..');
const requireVite = createRequire(realpathSync(resolve(root, 'admin/node_modules/vite/package.json')));
const { minifySync } = await import(pathToFileURL(requireVite.resolve('rolldown/utils')));
const checking = process.argv.includes('--check');
const files = {
  'app.js': 'miniprogram/app.js',
  'members.js': 'miniprogram/pages/members/index.js',
  'manage.js': 'miniprogram/pages/family-manage/index.js',
  'read.js': 'miniprogram/pages/family-profile/index.js',
  'edit.js': 'miniprogram/pages/family-profile-edit/index.js',
  'fields.js': 'miniprogram/utils/family-profile.js'
};
for (const [name, target] of Object.entries(files)) {
  const input = readFileSync(resolve(root, 'assets/family-profile', name), 'utf8');
  const result = minifySync(name, input, { compress: true, mangle: { toplevel: true, reserved: ['module', 'exports', 'require'] } });
  if (result.errors && result.errors.length) throw new Error(JSON.stringify(result.errors));
  const output = '// Generated by scripts/package-family-profile.mjs; edit assets/family-profile/' + name + '\n' + result.code + '\n';
  if (checking) {
    if (readFileSync(resolve(root, target), 'utf8') !== output) throw new Error('家谱资料发布副本不同步：' + target);
  } else writeFileSync(resolve(root, target), output);
}
console.log('家谱资料可维护源码与压缩副本' + (checking ? '一致' : '已同步'));
